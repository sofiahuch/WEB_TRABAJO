export function seedCatalogue(db) {
  if (db.prepare("SELECT COUNT(*) AS total FROM items").get().total > 0) return;
  const insert = db.prepare(`INSERT INTO items
    (title, type, creator, year, description, minutes, session_label, mood)
    VALUES (?, ?, ?, ?, ?, ?, ?, ?)`);
  db.exec("BEGIN");
  try {
    for (const item of initialItems) insert.run(...item);
    db.exec("COMMIT");
  } catch (error) {
    db.exec("ROLLBACK");
    throw error;
  }
}
